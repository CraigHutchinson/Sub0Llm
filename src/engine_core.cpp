// ============================================================================
//  Runtime BPE tokenizer (loaded from tokenizer.tok) -- state declared up top
//  (g_tok) so save_model/load_model can fingerprint-guard the decoder/model pair.
// ============================================================================

std::uint64_t tokenizer_fingerprint() { return g_tok.loaded ? tok::fingerprint(g_tok) : 0; }

bool load_tokenizer(const char* path) {
    std::ifstream is(path, std::ios::binary);
    if (!is) { std::println(stderr, "tokenizer: cannot open '{}'", path); return false; }
    tok::Tokenizer t;
    if (!tok::deserialize(t, is)) { std::println(stderr, "tokenizer: bad or truncated '{}'", path); return false; }
    if (t.vocab != VOCAB)
        std::println(stderr, "tokenizer: vocab {} != built-in VOCAB {} (stale artifact?)", t.vocab, VOCAB);
    g_tok = std::move(t);
    // If a model is already loaded (gen loads the model first, then the tokenizer), refuse a decoder
    // that does not match the vocab those weights were trained against -- a loud, actionable failure
    // instead of silently detokenizing to garble.
    if (tok_model_conflict()) { warn_tok_model_mismatch(); g_tok = {}; return false; }
    return true;
}

std::vector<int> encode(const std::string& text) { return tok::encode(g_tok, text); }

