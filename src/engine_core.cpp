// ============================================================================
//  Serialization (header validates the generated config)
// ============================================================================
// The on-disk format is one backend-agnostic blob: a Header that pins the constexpr
// config, then PARAM_FLOATS floats in PARAM_LAYOUT order. Reading/writing goes
// through params_ptr() so a device backend can stage the weights via the sync hooks
// without changing the file format.

namespace {
struct Header {
    char magic[4] = {'S', '0', 'L', '5'};
    int d_model = D_MODEL, n_layers = N_LAYERS, n_heads = N_HEADS;
    int d_ff = D_FF, seq_len = SEQ_LEN, vocab = VOCAB, ternary = USE_TERNARY;
    int pos_encoding = static_cast<int>(POS_ENCODING);   // 0 = absolute learned, 1 = RoPE
    uint64_t param_floats = PARAM_FLOATS;
};

// The runtime tokenizer state (loaded from tokenizer.tok). Loading, encoding and detokenizing all
// delegate to the shared sub0::tok library (src/tokenizer.cpp) -- the single definition the build-time
// configurator uses too, so prompts encode byte-identically to how the corpus was tokenized at build.
tok::Tokenizer g_tok;

// Tokenizer fingerprint stamped in the last model loaded (0 = unknown: a legacy model without the
// trailer, or no model loaded). A trained model is only meaningful decoded by the vocab it was trained
// against; this pins that identity so a mismatched decoder fails loudly rather than emitting garble.
std::uint64_t g_model_tok_fp = 0;

// True iff BOTH a model and a tokenizer are loaded with KNOWN fingerprints that disagree -- i.e. the
// decoder does not match the vocab the weights were trained with. Whichever of load_model /
// load_tokenizer completes the pair second calls this, so the order does not matter.
bool tok_model_conflict() {
    return g_model_tok_fp != 0 && g_tok.loaded && tok::fingerprint(g_tok) != g_model_tok_fp;
}

// A shared, actionable message for the mismatch (both load paths print it).
void warn_tok_model_mismatch() {
    std::println(stderr,
        "error: tokenizer does not match the vocabulary this model was trained with "
        "(fingerprint {:#018x} != {:#018x}).\n"
        "       Decoding would produce garble. This usually means the build's tokenizer.tok was "
        "regenerated by a later `configure` for a different corpus.\n"
        "       Fix: use the tokenizer.tok bundled in the model's directory, or re-run `configure` "
        "on the SAME corpus this model was trained on to regenerate the matching vocab.",
        tok::fingerprint(g_tok), g_model_tok_fp);
}
}

void save_model(const char* path) {
    sync_params_to_host();                       // pull live weights into the host staging buffer
    std::ofstream os(path, std::ios::binary);
    Header h;
    os.write((const char*)&h, sizeof(h));
    os.write((const char*)params_ptr(), (std::streamsize)(PARAM_FLOATS * sizeof(float)));
    // Trailing 8-byte tokenizer fingerprint: stamps WHICH vocab these weights were trained against so a
    // mismatched decoder is caught on load (0 when no tokenizer is loaded). Appended after the params so
    // a legacy reader that stops at PARAM_FLOATS is unaffected -- and a legacy file (no trailer) simply
    // reads back as fingerprint 0 (unknown), i.e. no guard. No format-magic bump needed.
    const std::uint64_t fp = g_tok.loaded ? tok::fingerprint(g_tok) : 0;
    os.write((const char*)&fp, sizeof(fp));
}

bool load_model(const char* path) {
    std::ifstream is(path, std::ios::binary);
    if (!is) return false;
    Header h, ref;
    is.read((char*)&h, sizeof(h));
    if (std::memcmp(h.magic, ref.magic, 4) != 0 ||
        h.d_model != ref.d_model || h.n_layers != ref.n_layers || h.n_heads != ref.n_heads ||
        h.d_ff != ref.d_ff || h.seq_len != ref.seq_len || h.vocab != ref.vocab ||
        h.ternary != ref.ternary || h.pos_encoding != ref.pos_encoding ||
        h.param_floats != ref.param_floats) {
        std::println(stderr, "error: model was built with a different (constexpr) config");
        return false;
    }
    is.read((char*)params_ptr(), (std::streamsize)(PARAM_FLOATS * sizeof(float)));
    if (!is) return false;
    sync_params_to_device();                     // push the loaded weights to the live (device) copy
    // Optional trailing tokenizer fingerprint (see save_model). A legacy model has none -> read fails
    // and leaves the fingerprint unknown (0 = no guard). If a tokenizer is already loaded, catch a
    // mismatch now (covers the load-tokenizer-then-load-model order; gen does the reverse).
    std::uint64_t fp = 0;
    is.read((char*)&fp, sizeof(fp));
    g_model_tok_fp = (is.gcount() == static_cast<std::streamsize>(sizeof(fp))) ? fp : 0;
    if (tok_model_conflict()) { warn_tok_model_mismatch(); return false; }
    return true;
}

